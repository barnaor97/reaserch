# =============================================================== §7 within-class ranking rationale
rows = []
for pop, u in zip(["documented", "model"], unit_rows):
    uu = u[u.land_cover.notna() & u.RIS_balanced.notna()]
    grand = float(uu.RIS_balanced.mean())
    gm = uu.groupby("land_cover").RIS_balanced
    ss_between = float(((gm.mean() - grand) ** 2 * gm.size()).sum())
    ss_total = float(((uu.RIS_balanced - grand) ** 2).sum())
    rows.append(dict(quantity="unit RIS (Balanced)", population=pop, n=len(uu),
                     eta_squared_between_class=ss_between / ss_total,
                     pct_variance_within_class=100.0 * (1 - ss_between / ss_total),
                     mean_within_class_sd=float(gm.std().mean()),
                     sd_of_class_means=float(gm.mean().std())))
bp = pd.DataFrame({"cls": CLS_PX[S1], "b17": B17[S1]})
bp = bp[bp.cls.isin(CLASSES)]
grand = float(bp.b17.mean())
g = bp.groupby("cls").b17
ss_between = float(((g.mean() - grand) ** 2 * g.size()).sum())
ss_total = float(((bp.b17 - grand) ** 2).sum())
rows.append(dict(quantity="baseline NBR 2017 (the denominator)", population="sampled burned pixels",
                 n=len(bp), eta_squared_between_class=ss_between / ss_total,
                 pct_variance_within_class=100.0 * (1 - ss_between / ss_total),
                 mean_within_class_sd=float(g.std().mean()), sd_of_class_means=float(g.mean().std())))
within = pd.DataFrame(rows)
save_table("t07_within_vs_between_class_variability", within,
           "Evidence for the NARROW claim about within-class ranking. `eta_squared_between_class` is the "
           "share of variance attributable to land-cover class. Comparing units inside one fixed 2018 "
           "class removes the between-class component of the baseline differences; it does NOT remove "
           "the within-class component, which the table shows is substantial. Within-class ranking "
           "therefore reduces, and does not eliminate, dependence on baseline spectral state.",
           "spatial units (RIS rows) and sampled 10 m burned pixels (baseline row) — stated per row",
           {"unit RIS": "nb17_t05_units_*", "baseline NBR": "nbr_raw.npy columns 0:12"}, section="7")
print("[§7] baseline NBR: %.1f%% of variance is WITHIN class" % within.iloc[-1].pct_variance_within_class)

