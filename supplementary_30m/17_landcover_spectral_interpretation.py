def dist(v, prefix=""):
    v = np.asarray(v, dtype=float)
    v = v[np.isfinite(v)]
    if not v.size:
        return {}
    q = np.percentile(v, [5, 25, 50, 75, 95])
    return {prefix + "n": int(v.size), prefix + "mean": float(v.mean()), prefix + "median": float(q[2]),
            prefix + "p5": float(q[0]), prefix + "p25": float(q[1]), prefix + "p75": float(q[3]),
            prefix + "p95": float(q[4]), prefix + "iqr": float(q[3] - q[1]), prefix + "sd": float(v.std())}


