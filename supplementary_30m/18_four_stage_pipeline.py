def save_table(stem, df, caption, support, sources, section):
    stem = PREFIX + stem
    df.to_csv(os.path.join(TAB, stem + ".csv"), index=False)
    head = ["<!-- generated by notebooks/18_four_stage_pipeline.py §%s on %s -->" % (section, RUN), "",
            caption, "", "**Statistical support: %s**" % support, "", "**Sources.**", ""]
    head += ["- `%s` — %s" % (k, v) for k, v in sources.items()]
    cols = list(df.columns)
    body = ["", "| " + " | ".join(str(c) for c in cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        body.append("| " + " | ".join(
            ("%.4f" % r[c]) if isinstance(r[c], (float, np.floating)) and np.isfinite(r[c])
            else ("" if isinstance(r[c], (float, np.floating)) else str(r[c])) for c in cols) + " |")
    open(os.path.join(TAB, stem + ".md"), "w").write("\n".join(head + body) + "\n")
    REGISTRY.append(dict(section=section, kind="table", stem=stem, support=support,
                         caption=caption.split(".")[0]))
    print("\n[table] %s  (%d rows)  support: %s" % (stem, len(df), support))
    return df


