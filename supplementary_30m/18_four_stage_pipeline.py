"""
18_four_stage_pipeline.py — where between-land-cover relationships change along the pipeline.

Supersedes nothing: nb16 and nb17 stay on disk as the sampled-support diagnostics they were.
Nothing is retrained, redefined or rebuilt. 15_polygon_workflow.py units are reused, not recreated.

THE FOUR STAGES, and the support each one legitimately has:

  A  OBSERVED spectral change      observed_nbr_loss = observed_NBR_2017 - observed_NBR_2025,
                                   from VALID monthly observations only.
                                   Full-ROI 30 m raster (data/raw/nbr_2017_2025_30m.tif) AND
                                   sampled 10 m pixels (nbr_raw + X_scaled_mask).
  B  IMPUTED spectral change       imputed_nbr_loss, the series compute_targets() actually used.
                                   Gaps filled with a GLOBAL per-calendar-month mean
                                   (04_data_prep cell 9). Sampled 10 m pixels only.
  C  ANALYTICAL Recovery Gap       clip(imputed_nbr_loss / (|imputed_NBR_2017| + 1e-6), 0, 1).
                                   Sampled 10 m pixels only. Never a full-ROI raster.
  D  PREDICTED Recovery Gap        L-TAE prediction of C. Full-ROI 30 m raster and sampled
                                   test pixels.

A is NOT "the Recovery Gap numerator". It is an observational analogue of it computed from valid
observations; B is the numerator. Keeping them apart is the point of this module.

Run: python notebooks/18_four_stage_pipeline.py
Writes outputs/tables/nb18_*.{csv,md}, outputs/figures/nb18_*.png
"""
