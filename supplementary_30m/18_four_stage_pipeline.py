sens_rows = []
for label, thr in [("any valid observation", 1), (">= 6 valid months in both years", 6),
                   (">= 9 valid months in both years", 9), ("all 12 months in both years", 12)]:
    keep = elig_cells & (NV17 >= thr) & (NV25 >= thr)
    for c in CLS_ORDER:
        m = keep & (CLSG == c)
        if m.sum() < MIN_CLASS_N: continue
        sens_rows.append(dict(threshold=label, min_valid_months=thr, land_cover=c, n_cells=int(m.sum()),
                              pct_of_class_retained=100.0 * float(m.sum() / max((elig_cells & (CLSG == c)).sum(), 1)),
                              observed_nbr_loss=float(np.nanmean(OBS_LOSS[m]))))
