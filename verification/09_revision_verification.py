# 7. Table 9 re-verification from the stored test-set predictions
import json as _json
pred = np.load(os.path.join(ROOT, 'models', 'main', 'predictions_test.npz'))
splits = _json.load(open(os.path.join(P, 'splits.json')))
te = np.array(splits['test'])
burned_te = np.asarray(y[te]).astype(bool).any(axis=1)
rows = []
for k in ('severity', 'persistence', 'recovery_gap'):
    t, p_ = aux[k][te], pred[k].ravel()
    for lab, m in (('All test pixels', np.ones(len(te), bool)), ('Burned only', burned_te)):
        e = p_[m] - t[m]
        rows.append(dict(indicator=k, population=lab, n=int(m.sum()),
                         pearson_r=float(stats.pearsonr(t[m], p_[m])[0]),
                         spearman_rho=float(stats.spearmanr(t[m], p_[m]).statistic),
                         MAE=float(np.abs(e).mean()), RMSE=float(np.sqrt((e ** 2).mean())),
                         R2=float(1 - (e ** 2).sum() / ((t[m] - t[m].mean()) ** 2).sum())))
write('nb09_t08_table9_reverification', pd.DataFrame(rows),
      'Table 9 of the thesis, recomputed from models/main/predictions_test.npz and the '
      'stored analytical targets, to confirm every published value.')
