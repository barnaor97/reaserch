# 6. Study-area environmental characterisation (Section 3.2.1)
# ---------------------------------------------------------------------
# Climate from WorldClim 2.1 (Fick and Hijmans, 2017), 10 arc-minute
# bioclimatic surfaces, sampled over the ROI bounding box. Topography from
# the SRTM 30 m digital elevation model (Farr et al., 2007), sampled on a
# regular 9 x 11 grid through the OpenTopoData API. Both are external
# products; this section records exactly what was read from them so the
# study-area description can be traced.
#
# Set CLIM_DIR to a directory holding wc2.1_10m_bio_{1,5,6,12,15,17}.tif
# (https://geodata.ucdavis.edu/climate/worldclim/2_1/base/wc2.1_10m_bio.zip)
# and set FETCH_DEM = True to re-query the elevation API.
CLIM_DIR = os.environ.get('WORLDCLIM_10M_DIR', '')
FETCH_DEM = os.environ.get('FETCH_DEM', '') == '1'
BBOX = (34.2672, 31.0574, 34.7820, 31.7495)   # W, S, E, N  (nb09_t04)

if CLIM_DIR and os.path.isdir(CLIM_DIR):
    import rasterio
    from rasterio.windows import from_bounds
    BIO = {'bio_12': 'annual precipitation (mm)',
           'bio_1': 'annual mean temperature (C)',
           'bio_5': 'max temperature of the warmest month (C)',
           'bio_6': 'min temperature of the coldest month (C)',
           'bio_15': 'precipitation seasonality (CV, %)',
           'bio_17': 'precipitation of the driest quarter (mm)'}
    rows = []
    for var, lab in BIO.items():
        with rasterio.open(os.path.join(CLIM_DIR, 'wc2.1_10m_%s.tif' % var)) as src:
            a = src.read(1, window=from_bounds(*BBOX, src.transform)).astype(float)
            a[a < -1e30] = np.nan
            rows.append(dict(variable=lab, minimum=float(np.nanmin(a)),
                             mean=float(np.nanmean(a)), maximum=float(np.nanmax(a)),
                             northern_edge=float(np.nanmean(a[0])),
                             southern_edge=float(np.nanmean(a[-1]))))
    write('nb09_t06_climate_worldclim', pd.DataFrame(rows),
          'Climate of the region of interest, read from the WorldClim 2.1 10 arc-minute '
          'bioclimatic surfaces (Fick and Hijmans, 2017) over the bounding box of '
          'nb09_t04. "northern edge" and "southern edge" are the means of the first and '
          'last grid rows, which give the north-south gradient across the ROI.')

if FETCH_DEM:
    import json as _json
    import urllib.request
    import time
    lats = np.linspace(BBOX[1], BBOX[3], 11)
    lons = np.linspace(BBOX[0], BBOX[2], 9)
    pts = [(la, lo) for la in lats for lo in lons]
    vals = []
    for k in range(0, len(pts), 50):
        loc = '|'.join('%f,%f' % p for p in pts[k:k + 50])
        r = _json.load(urllib.request.urlopen(
            'https://api.opentopodata.org/v1/srtm30m?locations=' + loc, timeout=60))
        vals += [x['elevation'] for x in r['results'] if x['elevation'] is not None]
        time.sleep(1.2)
    v = np.array(vals, dtype=float)
    write('nb09_t07_topography_srtm',
          pd.DataFrame([dict(source='SRTM 30 m (Farr et al., 2007)', n_points=len(v),
                             minimum=v.min(), p25=np.percentile(v, 25),
                             median=np.median(v), p75=np.percentile(v, 75),
                             maximum=v.max(), mean=v.mean())]),
          'Elevation over the region of interest, sampled on a regular 9 x 11 grid.')

